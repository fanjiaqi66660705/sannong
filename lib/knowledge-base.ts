/**
 * 基于关键词对知识库进行检索
 * @param query 用户问题
 * @param topK 返回最相关的前K条
 * @returns 相关知识条目列表
 */
export function searchKnowledge(query: string, topK = 3): KnowledgeItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  // 为每条知识计算相关度分数
  const scored = KNOWLEDGE_BASE.map((item) => {
    let score = 0;
    // 1. 关键词命中
    for (const kw of item.keywords) {
      if (q.includes(kw.toLowerCase())) {
        score += 2; // 关键词命中权重高
      }
    }
    // 2. 问题文本包含
    if (item.question.toLowerCase().includes(q) || q.includes(item.question.toLowerCase())) {
      score += 3;
    }
    // 3. 答案文本包含
    if (item.answer.toLowerCase().includes(q)) {
      score += 0.5;
    }
    // 4. 分类匹配
    if (q.includes(item.category.toLowerCase())) {
      score += 1;
    }
    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, topK)
    .map((s) => s.item);
}

/**
 * 拼接知识库上下文，供大模型参考
 */
export function buildContext(items: KnowledgeItem[]): string {
  if (items.length === 0) return "（未检索到相关知识库条目）";
  return items
    .map(
      (it, i) =>
        `【条目${i + 1}】分类：${it.category}\n问题：${it.question}\n答案：${it.answer}\n来源：${it.source}`
    )
    .join("\n\n");
}
